#!/usr/bin/env python3
"""Regenerates src/theme/omarchy.rs from an Omarchy checkout.

    git clone --depth 1 https://github.com/omacom/omarchy /tmp/omarchy
    python3 scripts/import-omarchy-themes.py /tmp/omarchy > src/theme/omarchy.rs
    cargo fmt

Every colour comes verbatim from themes/<slug>/colors.toml. Omarchy is MIT
licensed; see licenses/omarchy-MIT.txt.
"""
import os
import subprocess
import sys
import tomllib

# Display names as Omarchy's theme menu shows them. Unknown slugs get a
# title-cased name.
NAMES = {
    "catppuccin": "Catppuccin", "catppuccin-latte": "Catppuccin Latte", "ethereal": "Ethereal",
    "everforest": "Everforest", "flexoki-light": "Flexoki Light", "gruvbox": "Gruvbox",
    "hackerman": "Hackerman", "kanagawa": "Kanagawa", "last-horizon": "Last Horizon", "lumon": "Lumon",
    "lupine": "Lupine", "matte-black": "Matte Black", "miasma": "Miasma", "nord": "Nord",
    "osaka-jade": "Osaka Jade", "retro-82": "Retro 82", "ristretto": "Ristretto", "rose-pine": "Rosé Pine",
    "solitude": "Solitude", "starship": "Starship", "tokyo-night": "Tokyo Night", "vantablack": "Vantablack",
    "white": "White",
}
REQUIRED = [
    "accent", "selection", "muted", "background", "dark_background", "darker_background", "lighter_background",
    "foreground", "dark_foreground", "light_foreground", "bright_foreground", "red", "yellow", "green", "cyan",
    "blue", "magenta", "bright_red", "bright_yellow", "bright_green", "bright_cyan", "bright_blue", "bright_magenta",
]
OPTIONAL = ["orange", "brown"]


def hexv(s):
    s = s.strip().lstrip("#")
    assert len(s) == 6, s
    return "0x" + s.lower()


def main(root):
    sha = subprocess.run(["git", "-C", root, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    themes = os.path.join(root, "themes")
    out = [
        "//! Generated by scripts/import-omarchy-themes.py from omacom/omarchy (formerly basecamp/omarchy)",
        f"//! (commit {sha or 'unknown'}), themes/<slug>/colors.toml. Do not edit by hand.",
        "//! Omarchy is MIT licensed: see licenses/omarchy-MIT.txt.",
        "",
        "use super::Omarchy;",
        "",
        f'pub const OMARCHY_COMMIT: &str = "{sha}";',
        "",
        "pub const OMARCHY: &[Omarchy] = &[",
    ]
    for slug in sorted(os.listdir(themes)):
        f = os.path.join(themes, slug, "colors.toml")
        if not os.path.isfile(f):
            print(f"skipping {slug}: no colors.toml", file=sys.stderr)
            continue
        c = tomllib.load(open(f, "rb"))
        missing = [k for k in REQUIRED if k not in c]
        if missing:
            print(f"skipping {slug}: missing {missing}", file=sys.stderr)
            continue
        name = NAMES.get(slug, slug.replace("-", " ").title())
        out.append("    Omarchy {")
        out.append(f'        slug: "{slug}",')
        out.append(f'        name: "{name}",')
        out.append(f"        light: {'true' if c.get('mode') == 'light' else 'false'},")
        for k in REQUIRED:
            out.append(f"        {k}: {hexv(c[k])},")
        for k in OPTIONAL:
            out.append(f"        {k}: {'Some(' + hexv(c[k]) + ')' if k in c else 'None'},")
        out.append("    },")
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp/omarchy")
